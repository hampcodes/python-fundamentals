# Concatenación
name = 'Henry'
last_name = 'Mendoza'
age = 45

# Usa f-strings para insertar variables dentro del texto
full_name = f'{name} {last_name}'

# Inserta nombre completo y edad dentro del mensaje
message = f'{full_name}, tienes {age} años'

# Imprime el mensaje final
print(message)  # Henry Mendoza, tienes 5 años

